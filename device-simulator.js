#!/usr/bin/env node

/**
 * Simple IoT Device Simulator for Testing WebSocket Smart Home System
 * 
 * This script simulates an IoT device (like ESP32) connecting to the WebSocket room
 * and sending periodic status updates.
 * 
 * Usage:
 *   node device-simulator.js
 * 
 * Configuration:
 *   - API_URL: Cloudflare Worker API endpoint
 *   - DEVICE_ID: Which device to simulate (must exist in database)
 *   - DEVICE_TYPE: Type of device (light, thermostat, etc.)
 *   - SIMULATE_COMMANDS: Whether to respond to commands with status updates
 */

import WebSocket from 'ws';

// ============= CONFIGURATION =============
const API_URL = (process.env.API_URL || 'http://localhost:8787').replace(/\/+$/, '');
const WS_URL = (process.env.WS_URL || API_URL.replace(/^https:/, 'wss:').replace(/^http:/, 'ws:')).replace(/\/+$/, '');
const DEVICE_ID = parseInt(process.env.DEVICE_ID || '1');
const DEVICE_TYPE = process.env.DEVICE_TYPE || 'light';
const DEVICE_NAME = process.env.DEVICE_NAME || 'Simulated Device';
const API_KEY = process.env.DEVICE_API_KEY || '';
const SIMULATE_COMMANDS = process.env.SIMULATE_COMMANDS !== 'false';

// ============= STATE =============
let ws = null;
let sessionId = null;
let currentPower = 'off';
let doorLocked = true;
let isConnected = false;
let reconnectTimer = null;
let connecting = false;
let connectedHouseId = null;

// ============= LOGGING =============
function log(message, type = 'INFO') {
  const timestamp = new Date().toISOString();
  console.log(`[${timestamp}] [${type}] ${message}`);
}

function logError(message) {
  log(message, 'ERROR');
}

function logSuccess(message) {
  log(message, 'SUCCESS');
}

function logWebSocket(message) {
  log(message, 'WS');
}

// ============= DEVICE AUTHENTICATION =============
/** Exchange the one-time pairing key for a short-lived, device-bound ticket. */
async function getDeviceTicket() {
  if (!/^[a-f0-9]{64}$/i.test(API_KEY)) {
    throw new Error('Set DEVICE_API_KEY to the 64-character pairing key generated by the ReMan dashboard.');
  }

  const response = await fetch(`${API_URL}/ws/device-ticket`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${API_KEY}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({ deviceId: DEVICE_ID })
  });

  const result = await response.json().catch(() => ({}));
  if (!response.ok || !result.ticket || !result.houseId) {
    throw new Error(result.error || `Device ticket request failed (${response.status})`);
  }

  connectedHouseId = Number(result.houseId);
  if (!Number.isSafeInteger(connectedHouseId) || connectedHouseId <= 0) {
    throw new Error('The pairing service returned an invalid property ID.');
  }
  return { ticket: result.ticket, sessionId: result.sessionId };
}

// ============= WEBSOCKET MANAGEMENT =============
/**
 * Connect to WebSocket room as IoT device
 */
async function connectToWebSocket() {
  if (connecting || isConnected) return;
  connecting = true;
  try {
    // A physical device authenticates with its one-time pairing key, never a
    // reusable administrator password or browser JWT.
    const { ticket, sessionId: sid } = await getDeviceTicket();
    sessionId = sid;

    const wsUrl = `${WS_URL}/ws/house/${connectedHouseId}?ticket=${encodeURIComponent(ticket)}`;
    logWebSocket(`Connecting to the authenticated house room for property ${connectedHouseId}...`);

    ws = new WebSocket(wsUrl);

    ws.on('open', () => {
      connecting = false;
      isConnected = true;
      logWebSocket(`✓ WebSocket connected (sessionId: ${sessionId})`);
      sendInitialStatus();
    });

    ws.on('message', (data) => {
      try {
        const message = JSON.parse(data);
        handleWebSocketMessage(message);
      } catch (e) {
        logError(`Failed to parse message: ${e.message}`);
      }
    });

    ws.on('error', (error) => {
      logError(`WebSocket error: ${error.message}`);
      isConnected = false;
      connecting = false;
      scheduleReconnect(5000);
    });

    ws.on('close', () => {
      logWebSocket(`WebSocket closed`);
      isConnected = false;
      connecting = false;
      scheduleReconnect(5000);
    });

  } catch (error) {
    connecting = false;
    logError(`Connection failed: ${error.message}`);
    scheduleReconnect(10000);
  }
}

function scheduleReconnect(delayMs) {
  if (reconnectTimer) return;
  log(`Will reconnect in ${Math.round(delayMs / 1000)} seconds...`);
  reconnectTimer = setTimeout(() => {
    reconnectTimer = null;
    void connectToWebSocket();
  }, delayMs);
}

/**
 * Send initial device status when connected
 */
function sendInitialStatus() {
  if (!isConnected || ws?.readyState !== WebSocket.OPEN) return;

  logWebSocket(`Sending initial device status...`);
  ws.send(JSON.stringify({
    type: 'device_update',
    deviceId: DEVICE_ID,
    status: 'online',
    data: {
      deviceName: DEVICE_NAME,
      deviceType: DEVICE_TYPE,
      power: currentPower,
      doorLocked,
      temperature: Number((Math.random() * 10 + 20).toFixed(1)),
      humidity: Number((Math.random() * 30 + 40).toFixed(1))
    },
    timestamp: new Date().toISOString()
  }));
}

/**
 * Handle incoming WebSocket messages
 */
function handleWebSocketMessage(message) {
  logWebSocket(`Received: ${message.type}`);

  switch (message.type) {
    case 'connected':
      logSuccess(`✓ Joined house room as device`);
      break;

    case 'user_joined':
      log(`👤 ${message.clientType || 'Client'} joined (ID: ${message.userId})`);
      break;

    case 'user_left':
      log(`👤 ${message.clientType || 'Client'} left (ID: ${message.userId})`);
      break;

    case 'device_command':
      if (Number(message.deviceId) === DEVICE_ID) {
        void handleDeviceCommand(message);
      }
      break;

    case 'ping':
      if (isConnected) {
        ws.send(JSON.stringify({
          type: 'pong',
          timestamp: new Date().toISOString()
        }));
      }
      break;

    case 'error':
      logError(`Server error: ${message.error || message.message || 'Unknown error'}`);
      break;

    default:
      log(`Unhandled message type: ${message.type}`);
  }
}

/**
 * Handle incoming device commands (e.g., turn on/off)
 */
async function handleDeviceCommand(message) {
  log(`📥 Received command: ${message.command}`);

  if (!SIMULATE_COMMANDS) {
    log(`Command simulation disabled`);
    return;
  }

  let success = true;
  let responseMessage = 'Command executed (simulated).';
  const command = String(message.command || '').toLowerCase();

  if (command === 'io.set') {
    currentPower = message.state ? 'on' : 'off';
    responseMessage = `Relay ${message.id || ''} set ${currentPower}.`;
  } else if (['on', 'turn_on'].includes(command)) {
    currentPower = 'on';
    responseMessage = 'Device turned on.';
  } else if (['off', 'turn_off'].includes(command)) {
    currentPower = 'off';
    responseMessage = 'Device turned off.';
  } else if (command === 'toggle') {
    currentPower = currentPower === 'on' ? 'off' : 'on';
    responseMessage = `Device toggled ${currentPower}.`;
  } else if (command === 'door.unlock') {
    doorLocked = false;
    responseMessage = 'Door unlocked (simulated).';
  } else if (command === 'door.lock') {
    doorLocked = true;
    responseMessage = 'Door locked (simulated).';
  } else if (command === 'fingerprint.status') {
    responseMessage = 'Fingerprint sensor connected (simulated).';
  } else if (command === 'fingerprint.register') {
    responseMessage = 'Fingerprint enrollment started (simulated).';
  } else if (command === 'fingerprint.delete') {
    responseMessage = 'Fingerprint template removed (simulated).';
  } else {
    success = false;
    responseMessage = `Unsupported simulated command: ${command}`;
  }

  if (message.commandId && ws?.readyState === WebSocket.OPEN) {
    ws.send(JSON.stringify({
      type: 'device_response',
      deviceId: DEVICE_ID,
      commandId: message.commandId,
      command: message.command,
      success,
      message: responseMessage,
      timestamp: new Date().toISOString()
    }));
  }

  if (success && command === 'fingerprint.register') {
    setTimeout(() => {
      if (!isConnected || ws?.readyState !== WebSocket.OPEN) return;
      ws.send(JSON.stringify({
        type: 'fingerprint.event',
        deviceId: DEVICE_ID,
        event: 'enrollment_complete',
        success: true,
        id: Number(message.id),
        message: 'Fingerprint enrolled (simulated).',
        timestamp: new Date().toISOString()
      }));
    }, 1500);
  }

  if (success && command === 'fingerprint.delete') {
    ws?.send(JSON.stringify({
      type: 'fingerprint.event',
      deviceId: DEVICE_ID,
      event: 'deleted',
      success: true,
      id: Number(message.id),
      message: 'Fingerprint removed (simulated).',
      timestamp: new Date().toISOString()
    }));
  }

  if (success) {
    setTimeout(() => sendStatusUpdate(responseMessage), 500);
  }
}

/**
 * Send periodic status updates (simulates sensor readings)
 */
function sendStatusUpdate(reason) {
  if (!isConnected || ws?.readyState !== WebSocket.OPEN) return;

  const temperature = Math.random() * 10 + 20;
  const humidity = Math.random() * 30 + 40;

  logWebSocket(`Sending status update: ${reason}`);
  ws.send(JSON.stringify({
    type: 'device_update',
    deviceId: DEVICE_ID,
    status: 'online',
    data: {
      deviceName: DEVICE_NAME,
      deviceType: DEVICE_TYPE,
      power: currentPower,
      doorLocked,
      temperature: Number(temperature.toFixed(1)),
      humidity: Number(humidity.toFixed(1)),
      batteryLevel: Number((Math.random() * 20 + 80).toFixed(1)),
      signal: Number((Math.random() * 30 + 60).toFixed(1)),
      reason
    },
    timestamp: new Date().toISOString()
  }));
}

/**
 * Start periodic status broadcasts
 */
function startStatusBroadcast() {
  // Send status every 30 seconds
  setInterval(() => {
    if (isConnected) {
      sendStatusUpdate('Periodic update');
    }
  }, 30000);

  // Also send a quick update after 5 seconds of connection
  setTimeout(() => {
    if (isConnected) {
      sendStatusUpdate('Post-connection status');
    }
  }, 5000);
}

// ============= STARTUP =============
console.log(`
╔════════════════════════════════════════╗
║   IoT Device Simulator                 ║
║   Smart Home WebSocket Testing         ║
╚════════════════════════════════════════╝

Configuration:
  API URL:        ${API_URL}
  WebSocket URL:  ${WS_URL}
  Device ID:      ${DEVICE_ID}
  Device Name:    ${DEVICE_NAME}
  Device Type:    ${DEVICE_TYPE}
  Property ID:    resolved from paired device
  Pairing Key:    ${API_KEY ? 'configured' : 'MISSING (set DEVICE_API_KEY)'}
  Simulate Cmds:  ${SIMULATE_COMMANDS}

Connecting...
`);

async function main() {
  if (!/^[a-f0-9]{64}$/i.test(API_KEY)) {
    logError('Set DEVICE_API_KEY to the 64-character pairing key generated by the ReMan dashboard.');
    process.exit(1);
  }
  try {
    await connectToWebSocket();
    startStatusBroadcast();
  } catch (error) {
    logError(`Fatal error: ${error.message}`);
    process.exit(1);
  }
}

process.on('SIGINT', () => {
  log('Shutting down...');
  if (reconnectTimer) clearTimeout(reconnectTimer);
  if (ws) {
    ws.close();
  }
  process.exit(0);
});

main();
